import re
import json

def handle_dialog(cmd, cmd_line, ask_ai_fn):
    # Проверяем триггеры
    triggers = ["уточни", "перефразируй", "что ты имел в виду", "диалог", "уточнение"]
    if not any(t in cmd_line.lower() for t in triggers):
        return False
    
    print("💬 Диалоговый режим:")
    print("   Я помогу уточнить твой запрос.")
    
    # Извлекаем вопрос или тему
    match = re.search(r'(?:уточни|перефразируй|что ты имел в виду|диалог)\s+(.+?)$', cmd_line, re.IGNORECASE)
    if match:
        topic = match.group(1).strip()
        print(f"   Ты спросил: {topic}")
        
        # Спрашиваем модель для уточнения
        prompt = f"""Пользователь спросил: "{topic}"
        
        Задача: Уточни, что именно пользователь хочет сделать.
        
        Варианты уточнений:
        1. Что именно нужно сделать?
        2. Для какого проекта?
        3. Есть ли конкретные требования?
        
        Верни краткий, дружелюбный ответ с уточняющими вопросами."""
        
        response = ask_ai_fn(prompt)
        print(f"\n🤖 {response}")
        
        # Запоминаем диалог для контекста
        print("\n💡 Можешь ответить, и я продолжу диалог.")
        
    else:
        # Если нет конкретного вопроса — просто показываем помощь
        print("""
📖 Диалоговый режим помогает уточнить запрос.

Примеры:
  • уточни, что ты имел в виду под 'погода'
  • перефразируй запрос 'сделай проект'
  • что ты имел в виду когда сказал 'апи'

Я помогу тебе сформулировать запрос точнее.
""")
    
    return True